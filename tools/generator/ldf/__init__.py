__all__ = ["ldf"]

from . import ascyacc


def post_process_messages(p):
    p["Messages"] = []
    frames = p.get("frames", {})
    signals = p.get("Signals", {})
    for name, frame in frames.items():
        msg = {"Name": name, "Id": frame["Id"], "Node": frame["Publisher"], "Dlc": frame["Dlc"], "Signals": []}
        for sname, sigi1 in frame["Signals"].items():
            sigi2 = signals[sname]
            size = eval(sigi2["Size"])
            signal = {
                "Name": sname,
                "Start": sigi1["Start"],
                "Size": sigi2["Size"],
                "Endian": "little",
                "Sign": "+",
                "Factor": 1,
                "Offset": 0,
                "Min": 0,
                "Max": (1 << size - 1),
                "Unit": "",
                "InitValue": sigi2["Initial"],
                "Node": sigi2["Subscriber"],
            }
            msg["Signals"].append(signal)
        msg["Signals"].sort(key=lambda x: eval(x["Start"]))
        p["Messages"].append(msg)
    p["Messages"].sort(key=lambda x: eval(x["Id"]))


def parse(file):
    print(f"LDF: {file}")
    fp = open(file, "r")
    data = fp.read()
    fp.close()
    p = ascyacc.parse(data)
    post_process_messages(p)
    return p


def save_dbc(p, dbc):
    f = open(dbc, "w")
    nodes = []
    for msg in p["Messages"]:
        if msg["Node"] not in nodes:
            nodes.append(msg["Node"])
    f.write(
        """VERSION "generated by AS ldf tool"


NS_ :
    NS_DESC_
    CM_
    BA_DEF_
    BA_
    VAL_
    CAT_DEF_
    CAT_
    FILTER
    BA_DEF_DEF_
    EV_DATA_
    ENVVAR_DATA_
    SGTYPE_
    SGTYPE_VAL_
    BA_DEF_SGTYPE_
    BA_SGTYPE_
    SIG_TYPE_REF_
    VAL_TABLE_
    SIG_GROUP_
    SIG_VALTYPE_
    SIGTYPE_VALTYPE_
    BO_TX_BU_
    BA_DEF_REL_
    BA_REL_
    BA_DEF_DEF_REL_
    BU_SG_REL_
    BU_EV_REL_
    BU_BO_REL_
    SG_MUL_VAL_

BS_:

BU_: %s\n\n"""
        % (" ".join(nodes))
    )
    for msg in p["Messages"]:
        idx = eval(msg["Id"])
        f.write("\nBO_ %s %s: %s %s\n" % (idx, msg["Name"], msg["Dlc"], msg["Node"]))
        for sig in msg["Signals"]:
            f.write(
                ' SG_ %s : %s|%s@%s%s (%s,%s) [%s|%s] "" %s\n'
                % (
                    sig["Name"],
                    sig["Start"],
                    sig["Size"],
                    0 if sig["Endian"] == "big" else 1,
                    sig["Sign"],
                    sig["Factor"],
                    sig["Offset"],
                    sig["Min"],
                    sig["Max"],
                    ",".join(sig["Node"]),
                )
            )
    msgPeriod = {}
    schtbls = p["ScheduleTables"]
    for sname, schtbl in schtbls.items():
        period = 0
        for entry in schtbl:
            period = period + eval(entry["Delay"])
        for entry in schtbl:
            msgPeriod[entry["Name"]] = period

    f.write('\n\nCM_ " ";\n')
    f.write('BA_DEF_ BO_  "GenMsgCycleTime" INT 0 0;\n')
    f.write('BA_DEF_DEF_  "GenMsgCycleTime" 0;\n')
    for msg in p["Messages"]:
        if msg["Name"] in msgPeriod:
            idx = eval(msg["Id"])
            f.write('BA_ "GenMsgCycleTime" BO_ %s %s;\n' % (idx, msgPeriod[msg["Name"]]))
    f.write("\n\n\n\n\n\n")
    f.close()


def ldf(path, dbc=None):
    p = parse(path)
    if dbc != None:
        save_dbc(p, dbc)
    return p
